// Generates src/styles/tailwind-extras.css: every Tailwind utility the source
// uses, compiled with the project's theme mapping.
//
// Why: src/index.css is a frozen Tailwind build and Vite runs no Tailwind
// plugin, so any class added after that build silently does nothing. This uses
// the already-installed `tailwindcss` compiler directly (no extra packages).
// Re-run after adding classes:  npm run build:tw
//
// Long-term fix: add `@tailwindcss/vite` to vite.config.ts and delete this.

import { compile } from "tailwindcss";
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src");
const twDir = join(root, "node_modules", "tailwindcss");

// The project's token → utility mapping lives in globals.css' `@theme inline` block.
const globals = readFileSync(join(src, "styles", "globals.css"), "utf8");
const themeStart = globals.indexOf("@theme inline");
const themeEnd = globals.indexOf("\n}", themeStart) + 2;
const themeInline = globals.slice(themeStart, themeEnd);

const input = `
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities);
@custom-variant dark (&:is(.dark *));
${themeInline}
`;

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === "__preview" || name === "node_modules") continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx?|jsx?)$/.test(name)) out.push(p);
  }
  return out;
}

// Over-collect: every class-like token in string literals. Tailwind ignores
// anything that isn't a valid utility, so false positives cost nothing.
const candidates = new Set();
for (const file of walk(src)) {
  const text = readFileSync(file, "utf8");
  // Split on whitespace and string/template delimiters. (Matching string
  // literals is unreliable: apostrophes in JSX text break the pairing.)
  for (const token of text.split(/[\s"'`{}]+/)) {
    if (token && token.length < 120 && /^[!a-z0-9@\[-]/i.test(token)) candidates.add(token);
  }
}

const compiler = await compile(input, {
  base: root,
  async loadStylesheet(id, base) {
    const file = id.startsWith("tailwindcss/") ? join(twDir, id.slice("tailwindcss/".length)) : resolve(base, id);
    return { path: file, base: dirname(file), content: readFileSync(file, "utf8") };
  },
});

const css = compiler.build([...candidates]);
const out = join(src, "styles", "tailwind-extras.css");
writeFileSync(
  out,
  `/* GENERATED by scripts/build-tailwind-extras.mjs — do not edit. Run: npm run build:tw */\n${css}`,
);
console.log(`tailwind-extras.css: ${candidates.size} candidates scanned, ${(css.length / 1024).toFixed(0)} KB written`);
